// สร้าง src/data/journal/content/index.js (import ทุกบทความแบบ static สำหรับฝั่งเซิร์ฟเวอร์)
// รันอัตโนมัติก่อน build (npm run journal:index) — ห้ามแก้ index.js ด้วยมือ
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/data/journal/content");
const files = readdirSync(dir)
  .filter((f) => /^[a-z0-9-]+\.js$/.test(f) && f !== "index.js")
  .sort();
const id = (f) => "c_" + f.replace(/\.js$/, "").replace(/-/g, "_");
const out = `// AUTO-GENERATED by scripts/gen-journal-content-index.mjs — do not edit.
// Server-side only (api/seo-preview.js). The web app loads content per article via loadJournalContent().
${files.map((f) => `import ${id(f)} from "./${f}";`).join("\n")}

/** @type {Record<string, import("../articles").JournalContent>} */
export const JOURNAL_CONTENT = {
${files.map((f) => `  "${f.replace(/\.js$/, "")}": ${id(f)},`).join("\n")}
};
`;
writeFileSync(path.join(dir, "index.js"), out);
console.log(`journal content index: ${files.length} articles`);
