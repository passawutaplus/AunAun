#!/usr/bin/env node
/**
 * Redesign 2026: measure every image of existing works and events and print the SQL that
 * stores the sizes (cover_width, cover_height, media_sizes). It only reads: public rows through
 * the publishable key and the public image files. Review the SQL, then run it in the Supabase
 * SQL editor after migration 20261127100000_redesign_media_sizes_categories.sql.
 *
 * Usage (from Anthem-Code):
 *   node --env-file=.env.local scripts/redesign-backfill-media-sizes.mjs --out sizes.sql
 * Needs VITE_SUPABASE_URL and VITE_SUPABASE_PUBLISHABLE_KEY. Safe to run again: the SQL sets
 * the same values, and rows whose images could not be measured are left alone and listed.
 */
import sharp from "sharp";
import { writeFileSync } from "node:fs";

const url = process.env.VITE_SUPABASE_URL?.replace(/\/$/, "");
const key = process.env.VITE_SUPABASE_PUBLISHABLE_KEY;
if (!url || !key) {
  console.error("Set VITE_SUPABASE_URL and VITE_SUPABASE_PUBLISHABLE_KEY (e.g. --env-file=.env.local)");
  process.exit(2);
}
const outIdx = process.argv.indexOf("--out");
const outFile = outIdx >= 0 ? process.argv[outIdx + 1] : null;

const IMAGE_URL = /^https?:\/\/[^\s"']+\.(?:jpe?g|png|webp|gif|avif)(?:\?[^\s"']*)?$/i;

async function rows(table, select) {
  const out = [];
  for (let from = 0; ; from += 500) {
    const res = await fetch(`${url}/rest/v1/${table}?select=${select}&order=id`, {
      headers: { apikey: key, Authorization: `Bearer ${key}`, "Accept-Profile": "anthem", Range: `${from}-${from + 499}` },
    });
    if (!res.ok) throw new Error(`${table}: ${res.status} ${await res.text()}`);
    const page = await res.json();
    out.push(...page);
    if (page.length < 500) return out;
  }
}

/** Every image URL found anywhere inside a JSON value. */
function imageUrls(value, found = new Set()) {
  if (typeof value === "string") {
    if (IMAGE_URL.test(value)) found.add(value);
  } else if (Array.isArray(value)) {
    for (const v of value) imageUrls(v, found);
  } else if (value && typeof value === "object") {
    for (const v of Object.values(value)) imageUrls(v, found);
  }
  return found;
}

const cache = new Map();
/** [width, height] as a browser shows the image (EXIF rotation applied), or null. */
async function measure(src) {
  if (cache.has(src)) return cache.get(src);
  let size = null;
  try {
    const res = await fetch(src);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const meta = await sharp(Buffer.from(await res.arrayBuffer())).metadata();
    if (meta.width && meta.height) {
      size = (meta.orientation ?? 1) >= 5 ? [meta.height, meta.width] : [meta.width, meta.height];
    }
  } catch (err) {
    console.error(`  could not measure ${src}: ${err.message}`);
  }
  cache.set(src, size);
  return size;
}

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

async function build(table, select) {
  const sql = [];
  let measured = 0;
  let missing = 0;
  for (const row of await rows(table, select)) {
    const { id, cover_url: cover, ...rest } = row;
    const sets = [];
    const coverSize = cover ? await measure(cover) : null;
    if (cover && !coverSize) missing++;
    if (coverSize) {
      sets.push(`cover_width = ${coverSize[0]}`, `cover_height = ${coverSize[1]}`);
      measured++;
    }
    const sizes = {};
    for (const src of imageUrls(rest)) {
      const size = await measure(src);
      if (size) {
        sizes[src] = size;
        measured++;
      } else missing++;
    }
    if (Object.keys(sizes).length) sets.push(`media_sizes = media_sizes || ${lit(JSON.stringify(sizes))}::jsonb`);
    if (sets.length) sql.push(`UPDATE anthem.${table} SET ${sets.join(", ")} WHERE id = ${lit(id)};`);
  }
  console.error(`${table}: ${sql.length} rows, ${measured} images measured, ${missing} not measured`);
  return sql;
}

const statements = [
  "-- Generated by scripts/redesign-backfill-media-sizes.mjs — image sizes for the redesign.",
  "BEGIN;",
  ...(await build("projects", "id,cover_url,gallery_urls,content_blocks,context_images")),
  ...(await build("events", "id,cover_url,gallery_urls")),
  "COMMIT;",
  "",
].join("\n");

if (outFile) {
  writeFileSync(outFile, statements);
  console.error(`wrote ${outFile}`);
} else {
  process.stdout.write(statements);
}
